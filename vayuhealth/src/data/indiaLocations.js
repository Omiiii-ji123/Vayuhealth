/**
 * Get AQI color based on value
 */
export const getAQIColor = (aqi) => {
  if (aqi > 300) return "#7f0000";
  if (aqi > 200) return "#b388ff";
  if (aqi > 150) return "#ff3d00";
  if (aqi > 100) return "#ff9100";
  if (aqi > 50) return "#ffea00";
  return "#00e676";
};

/**
 * Get AQI status label based on value
 */
export const getAQIStatus = (aqi) => {
  if (aqi > 300) return "Hazardous";
  if (aqi > 200) return "Very Unhealthy";
  if (aqi > 150) return "Unhealthy";
  if (aqi > 100) return "Unhealthy Sensitive";
  if (aqi > 50) return "Moderate";
  return "Good";
};

/**
 * Get AQI emoji based on value
 */
export const getAQIEmoji = (aqi) => {
  if (aqi > 300) return "🚨";
  if (aqi > 200) return "🔴";
  if (aqi > 150) return "🟠";
  if (aqi > 100) return "🟡";
  if (aqi > 50) return "🟢";
  return "✅";
};

/**
 * Get locations by state
 */
export const getLocationsByState = (state) => {
  return indiaLocations.filter(loc => 
    loc.state.toLowerCase() === state.toLowerCase()
  );
};

/**
 * Get location by name
 */
export const getLocationByName = (name) => {
  return indiaLocations.find(loc => 
    loc.name.toLowerCase().includes(name.toLowerCase())
  );
};

/**
 * Get states with locations
 */
export const getStates = () => {
  const states = new Set(indiaLocations.map(loc => loc.state));
  return Array.from(states).sort();
};

/**
 * Get statistics about locations
 */
export const getLocationStats = () => {
  const total = indiaLocations.length;
  const states = getStates().length;
  const avgAqi = Math.round(
    indiaLocations.reduce((sum, loc) => sum + loc.aqi, 0) / total
  );
  const good = indiaLocations.filter(loc => loc.aqi <= 50).length;
  const moderate = indiaLocations.filter(loc => loc.aqi > 50 && loc.aqi <= 100).length;
  const unhealthy = indiaLocations.filter(loc => loc.aqi > 100).length;

  return {
    total,
    states,
    avgAqi,
    good,
    moderate,
    unhealthy,
    mostPolluted: [...indiaLocations].sort((a, b) => b.aqi - a.aqi).slice(0, 5),
    cleanest: [...indiaLocations].sort((a, b) => a.aqi - b.aqi).slice(0, 5),
  };
};

